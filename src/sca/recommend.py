"""Generate docs/recommendations.md from the marts, so every number traces to the data.

Delivery findings are REAL (Olist). Supplier lead-time, inventory and reorder-point findings come from the
SIMULATED layer and are labelled as such. The reorder-point impact is a counterfactual: the same demand and
the same supplier lead-time draws are replayed under a revised policy.

    python -m sca.recommend
"""
import math

import numpy as np
import pandas as pd

from . import db
from .config import ROOT
from .simulate import COVER_WEEKS, Z_SERVICE, simulate_series

MIN_STATE_ORDERS = 300
MIN_SUPPLIER_ORDERS = 50


def q(sql: str) -> pd.DataFrame:
    return pd.read_sql(sql, db.engine())


def _lead_draws(profile, seed: int):
    rng = np.random.default_rng(seed)
    return lambda: max(1, int(round(rng.lognormal(math.log(profile.actual_median_days), profile.lead_sigma))))


def reorder_point_counterfactual(max_series: int = 400) -> dict:
    """Replay at-risk series with s based on the supplier's observed p90 lead time instead of the quoted one."""
    cur = q("""SELECT product_key, warehouse_key, supplier_key, reorder_point, safety_stock, stockout_week_pct, fill_rate_pct
               FROM marts.inventory_position_current WHERE stockout_week_pct > 0""")
    prof = q("SELECT * FROM sim.supplier_profile").set_index("supplier_key")
    lt = q("SELECT supplier_key, sim_lead_p90_days FROM marts.supplier_lead_time").set_index("supplier_key")
    snap = q("""SELECT product_key, warehouse_key, d.date AS week, units_demand, on_hand, unit_cost
                FROM marts.inventory_snapshot i JOIN core.dim_date d ON d.date_key = i.snapshot_date_key
                ORDER BY 1, 2, 3""")
    snap["unit_cost"] = snap.unit_cost.astype(float)
    cur = cur.sort_values("stockout_week_pct", ascending=False).head(max_series)
    groups = {k: g for k, g in snap.groupby(["product_key", "warehouse_key"])}
    rows = []
    for r in cur.itertuples():
        g = groups[(r.product_key, r.warehouse_key)]
        d = g.units_demand.to_numpy()
        p = prof.loc[r.supplier_key]
        p90 = float(lt.loc[r.supplier_key].sim_lead_p90_days) if r.supplier_key in lt.index else float(p.quoted_lead_days)
        mu, sd = d.mean(), d.std()
        seed = int(r.product_key) * 1000 + int(r.warehouse_key)
        S_cover = max(2, math.ceil(mu * COVER_WEEKS))
        out = {}
        for name, lead_days in (("base", float(p.quoted_lead_days)), ("new", max(p90, float(p.quoted_lead_days)))):
            L = lead_days / 7 + 1
            safety = max(1, math.ceil(Z_SERVICE * sd * math.sqrt(L)))
            s = max(1, math.ceil(mu * L) + safety)
            res = simulate_series(d, s, s + S_cover, _lead_draws(p, seed))
            out[name] = (s, res.sold.sum() / max(d.sum(), 1), (res.on_hand == 0).mean(), (res.on_hand * g.unit_cost.to_numpy()).mean())
        rows.append({"product_key": r.product_key, "warehouse_key": r.warehouse_key,
                     "s_base": out["base"][0], "s_new": out["new"][0],
                     "fill_base": out["base"][1], "fill_new": out["new"][1],
                     "so_base": out["base"][2], "so_new": out["new"][2],
                     "inv_base": out["base"][3], "inv_new": out["new"][3]})
    df = pd.DataFrame(rows)
    return {"series": len(df), "changed": int((df.s_new > df.s_base).sum()),
            "fill_base": df.fill_base.mean() * 100, "fill_new": df.fill_new.mean() * 100,
            "so_base": df.so_base.mean() * 100, "so_new": df.so_new.mean() * 100,
            "inv_base": df.inv_base.sum(), "inv_new": df.inv_new.sum(), "detail": df}


def build_markdown() -> str:
    L: list[str] = []
    kpi = q("""SELECT sum(on_time_orders) o, sum(otd_eligible_orders) e, sum(orders) n, sum(canceled_orders) c,
                      round(avg(avg_review_score), 2) r FROM marts.kpi_delivery_monthly""").iloc[0]
    otd = 100 * kpi.o / kpi.e
    L += ["# Operational recommendations", "",
          "_Generated by `python -m sca.recommend` from the marts. Delivery numbers are **real Olist data (2016–2018)**. "
          "Anything labelled **[simulated]** comes from the synthetic inventory/PO layer and illustrates the method, "
          "not Olist sellers' actual stock._", "",
          f"**Baseline:** {int(kpi.n):,} orders · on-time delivery **{otd:.1f}%** · cancel rate {100 * kpi.c / kpi.n:.1f}%.", ""]

    # ---- 1. late-delivery states
    st = q(f"""SELECT state, orders, otd_pct, avg_days_late, avg_review_score FROM marts.delivery_by_state
               WHERE orders >= {MIN_STATE_ORDERS} ORDER BY otd_pct LIMIT 5""")
    nat = q("SELECT 100.0 * sum(on_time_orders) / sum(otd_eligible_orders) AS o FROM marts.kpi_delivery_monthly").o[0]
    L += ["## 1. Fix late deliveries in the weakest states (real)", "",
          "| State | Orders | On-time % | Avg days late | Avg review |", "|---|---:|---:|---:|---:|"]
    L += [f"| {r.state} | {r.orders:,} | {r.otd_pct} | {r.avg_days_late} | {r.avg_review_score} |" for r in st.itertuples()]
    rv = q("SELECT bucket, orders, avg_review_score FROM marts.review_vs_lateness ORDER BY sort_order")
    on, late = rv.iloc[0], rv.iloc[2]
    late_n = int(rv.orders.iloc[1:].sum())
    L += ["", f"**Why it matters:** on-time orders average a **{on.avg_review_score}** review; orders 4–7 days late average "
              f"**{late.avg_review_score}**. {late_n:,} orders ({100 * late_n / rv.orders.sum():.1f}%) arrived late.",
          f"**Action:** the five states above sit {nat - st.otd_pct.astype(float).mean():.1f} points below the national "
          f"{nat:.1f}%. Renegotiate carrier SLAs and widen the delivery estimate promised to these states — "
          "padding the estimate is the cheapest lever because on-time is measured against it.", ""]

    # ---- 2. suppliers
    real = q(f"""SELECT seller_id, orders, delivery_otd_pct, delivery_avg_days_late, avg_review_score
                 FROM marts.supplier_scorecard WHERE delivery_eligible_orders >= {MIN_SUPPLIER_ORDERS}
                 ORDER BY delivery_otd_pct, orders DESC LIMIT 5""")
    L += ["## 2. Put the worst suppliers on a corrective plan", "",
          f"**Real — lowest delivery on-time among sellers with ≥{MIN_SUPPLIER_ORDERS} orders:**", "",
          "| Seller | Orders | On-time % | Avg days late | Avg review |", "|---|---:|---:|---:|---:|"]
    L += [f"| …{r.seller_id[-6:]} | {r.orders:,} | {r.delivery_otd_pct} | {r.delivery_avg_days_late} | {r.avg_review_score} |"
          for r in real.itertuples()]
    sim = q("""SELECT seller_id, sim_po_count, sim_lead_mean_days, sim_lead_p90_days, sim_lead_stddev_days, sim_po_on_time_pct
               FROM marts.supplier_scorecard WHERE reliability_rank IS NOT NULL
               ORDER BY reliability_rank DESC LIMIT 5""")
    L += ["", "**[simulated] — least reliable replenishment lead times:**", "",
          "| Seller | POs | Mean lead (d) | p90 lead (d) | Std dev (d) | PO on-time % |", "|---|---:|---:|---:|---:|---:|"]
    L += [f"| …{r.seller_id[-6:]} | {r.sim_po_count} | {r.sim_lead_mean_days} | {float(r.sim_lead_p90_days):.1f} | "
          f"{r.sim_lead_stddev_days} | {r.sim_po_on_time_pct} |" for r in sim.itertuples()]
    L += ["", "**Action:** set a minimum on-time target (e.g. 90%), review monthly, and dual-source the SKUs that "
              "depend on the bottom suppliers. Use p90 — not the average — lead time when planning around them.", ""]

    # ---- 3. rebalance
    pairs = """FROM marts.inventory_position_current a
               JOIN marts.inventory_position_current b ON a.product_key = b.product_key AND a.warehouse_key <> b.warehouse_key
               WHERE a.risk_status IN ('stockout', 'at_risk') AND b.is_overstock"""
    reb = q(f"""SELECT right(p.product_id, 6) AS pid, p.category_en,
                      wa.warehouse_code AS short_dc, a.days_of_supply AS short_dos, a.risk_status AS short_status,
                      wb.warehouse_code AS long_dc,  b.days_of_supply AS long_dos, b.on_hand AS long_on_hand,
                      b.inventory_value AS long_value
               {pairs.replace('WHERE', 'JOIN core.dim_product p ON p.product_key = a.product_key JOIN core.dim_warehouse wa ON wa.warehouse_key = a.warehouse_key JOIN core.dim_warehouse wb ON wb.warehouse_key = b.warehouse_key WHERE')}
               ORDER BY b.inventory_value DESC LIMIT 8""")
    tot = q(f"""SELECT (SELECT count(*) FROM (SELECT DISTINCT a.product_key, a.warehouse_key, b.warehouse_key {pairs}) y) AS n,
                       COALESCE(sum(v), 0) AS value, COALESCE(sum(u), 0) AS units
                FROM (SELECT DISTINCT b.product_key, b.warehouse_key, b.inventory_value AS v, b.on_hand AS u {pairs}) x""").iloc[0]
    L += ["## 3. Rebalance stock between DCs **[simulated]**", "",
          f"{int(tot.n)} product/DC pairs are short at one DC while another DC holds >120 days of supply of the same SKU "
          f"({int(tot.units):,} excess units in total, {float(tot.value):,.0f} BRL at cost). The opportunity is **small**: overstock sits "
          "mostly in slow movers with a handful of units. Largest transfer candidates by value:", "",
          "| Product (category) | Short at | Days of supply | Excess at | Days of supply | Units there | Value |", "|---|---|---:|---|---:|---:|---:|"]
    L += [f"| …{r.pid} ({r.category_en}) | {r.short_dc} ({r.short_status}) | "
          f"{'0' if pd.isna(r.short_dos) else r.short_dos} | {r.long_dc} | {r.long_dos} | {int(r.long_on_hand)} | {float(r.long_value):,.0f} |"
          for r in reb.itertuples()]
    L += ["", "**Action:** check these transfers before placing new POs: they avoid the supplier lead time entirely. "
              "Do not expect a large working-capital release from this alone.", ""]

    # ---- 4. reorder points
    cf = reorder_point_counterfactual()
    st_ = q("""SELECT count(*) n, count(*) FILTER (WHERE risk_status='overstock') ov,
                      count(*) FILTER (WHERE risk_status='no_recent_demand') nd,
                      count(*) FILTER (WHERE risk_status IN ('stockout','at_risk')) risk FROM marts.inventory_position_current""").iloc[0]
    inv_delta = 100 * (cf["inv_new"] / cf["inv_base"] - 1) if cf["inv_base"] else 0
    L += ["## 4. Raise reorder points where the policy under-plans lead time **[simulated]**", "",
          f"The baseline policy plans with each supplier's *quoted* lead time. For the {cf['series']} product/DC series "
          f"with any stockout weeks, I replayed the same demand and the same lead-time draws with the reorder point "
          f"based on the supplier's observed **p90** lead time:", "",
          "| Metric | Current policy | Revised policy |", "|---|---:|---:|",
          f"| Reorder points raised | – | {cf['changed']} of {cf['series']} series |",
          f"| Average fill rate | {cf['fill_base']:.1f}% | {cf['fill_new']:.1f}% |",
          f"| Share of weeks in stockout | {cf['so_base']:.1f}% | {cf['so_new']:.1f}% |",
          f"| Average inventory value | {cf['inv_base']:,.0f} | {cf['inv_new']:,.0f} ({inv_delta:+.1f}%) |", "",
          "**Action:** apply the revised reorder points to the listed series, accept the extra inventory on unreliable-"
          "supplier SKUs, and re-run the simulation monthly with observed lead times.", "",
          f"**Context:** of {int(st_.n):,} product/DC series, {int(st_.risk)} are stocked out or at risk now, {int(st_.ov)} are "
          f"overstocked (>120 days), and {int(st_.nd):,} had no demand in the last 13 weeks — Olist demand is long-tail, so most "
          "SKU/DC pairs sell only occasionally. Slow movers are candidates for centralising in one DC rather than stocking in four.", "",
          "## Caveats", "",
          "- Delivery findings are from real 2016–2018 Brazilian marketplace data; they show the method, not today's performance.",
          "- All inventory and PO numbers come from a seeded simulation (see `docs/assumptions.md`). The stockout rate and fill rate "
          "depend on the simulated policy and lead-time parameters, so treat impact estimates as directional.",
          "- Seller IDs are truncated to their last six characters.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    out = ROOT / "docs" / "recommendations.md"
    out.write_text(build_markdown(), encoding="utf-8")
    print(f"wrote {out}")
